// node test_lifecycle.mjs (Flow). Mocked window/document/WebUI/gamepads/AudioContext; no browser needed.
import { createLifecycle } from './src/lifecycle.mjs';
let fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const target = () => { const L = {}; return { L, addEventListener(e, f) { (L[e] = L[e] || []).push(f); }, removeEventListener(e, f) { L[e] = (L[e] || []).filter((x) => x !== f); }, fire(e, ev) { (L[e] || []).slice().forEach((f) => f(ev || { preventDefault() { this.pd = true; } })); } }; };
const app = target(), win = Object.assign(target(), { Windows: { UI: { WebUI: { WebUIApplication: app } } } }), doc = Object.assign(target(), { visibilityState: 'visible', hidden: false, body: null }), canvas = target();
let pads = [], t = 0; const nav = { getGamepads: () => pads };
const ctx = { state: 'running', suspend() { this.state = 'suspended'; return Promise.resolve(); }, resume() { this.state = 'running'; return Promise.resolve(); } };
const ev = { sleep: 0, wake: 0, pause: [], err: 0 };
const lc = createLifecycle({ win, doc, nav, canvas, now: () => t, raf: () => 0, log: () => {}, getAudioCtx: () => ctx,
  onSleep: () => ev.sleep++, onWake: () => ev.wake++, onPauseRequest: (r) => ev.pause.push(r), onError: () => ev.err++ });
let dts = []; const f = (dt) => dts.push(dt);
t = 1000; lc.step(f); t = 1016; lc.step(f);
ok(dts[0] === 0 && Math.abs(dts[1] - 0.016) < 1e-9, 'first frame dt 0, then real dt');
doc.visibilityState = 'hidden'; doc.fire('visibilitychange');
ok(lc.asleep() && ctx.state === 'suspended' && ev.sleep === 1, 'hidden: sleeps, audio suspended, onSleep');
t = 9000; ok(lc.step(f) === false, 'hidden: frame skipped');
doc.visibilityState = 'visible'; doc.fire('visibilitychange');
ok(!lc.asleep() && ctx.state === 'running' && ev.wake === 1, 'visible: wakes, audio resumed');
dts = []; t = 9500; lc.step(f); t = 9516; lc.step(f);
ok(dts[0] === 0, 'clock re-synced on wake (no 8 s jump)');
app.fire('suspending'); ok(lc.asleep() && ctx.state === 'suspended', 'WebUI suspending sleeps');
app.fire('enteredbackground'); app.fire('resuming'); ok(lc.asleep(), 'still asleep while in background after resume');
app.fire('leavingbackground'); ok(!lc.asleep() && ctx.state === 'running' && ev.sleep === 2 && ev.wake === 2, 'leavingbackground wakes once');
win.fire('blur'); ok(ev.pause[0] === 'blur' && !lc.asleep(), 'blur asks for the pause menu, keeps rendering');
win.fire('focus'); win.fire('blur'); ok(ev.pause.length === 2, 'blur re-armed after focus');
pads = [{ connected: true }]; t = 20000; lc.step(f); pads = []; t = 20600; lc.step(f);
ok(ev.pause[2] === 'pad', 'controller drop (polled) asks for pause');
pads = [{ connected: true }]; win.fire('gamepadconnected'); pads = []; win.fire('gamepaddisconnected');
ok(ev.pause[3] === 'pad', 'controller drop (event) asks for pause');
const e = { preventDefault() { e.pd = true; } }; canvas.fire('webglcontextlost', e);
ok(e.pd && lc.asleep() && lc.stats.contextLost === 1, 'context lost: preventDefault + sleep');
canvas.fire('webglcontextrestored'); ok(!lc.asleep(), 'context restored: wakes');
let n = 0; const bad = () => { n++; throw new Error('boom'); };
t = 30000; lc.step(bad); t = 30016; lc.step(bad); lc.step(f);
ok(n === 2 && ev.err === 2 && lc.stats.errors === 2, 'frame errors caught, loop keeps going');
let rafs = 0, cbk; const lc2 = createLifecycle({ win: target(), doc: Object.assign(target(), { visibilityState: 'visible' }), nav, now: () => 0, raf: (g) => { rafs++; cbk = g; }, log: () => {} });
lc2.loop(bad); cbk(0); cbk(16); ok(rafs === 3, 'loop re-arms rAF even after a throw');
lc.dispose(); ok(!(doc.L.visibilitychange || []).length && !(app.L.suspending || []).length, 'dispose removes listeners');
console.log(fail ? fail + ' FAILED' : 'ALL PASS'); process.exit(fail ? 1 : 0);
